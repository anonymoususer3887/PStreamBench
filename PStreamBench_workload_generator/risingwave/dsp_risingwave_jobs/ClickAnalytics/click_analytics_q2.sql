-- Click Analytics (Q2): per-click geography lookup (country/city).
--
-- Mirrors com.kom.dsp.ClickAnalytics.ClickAnalytics (Flink) query 2 (see
-- GeographyOperator.java / GeoStats.java). Re-reading the reference
-- implementation closely: GeographyOperator is a plain ProcessFunction (no
-- keyBy, no window at all) -- for EVERY click event it does a fresh IP
-- lookup and emits exactly one GeoStats object with cityVisits={city: 1}.
-- So despite GeoStats having a Map<String,Integer> that looks like it
-- could accumulate counts, each individual invocation only ever populates
-- it with a single city at count 1 -- this is a genuinely STATELESS
-- per-event lookup+emit, not an aggregation, same shape as Sentiment
-- Analysis (no HOP/window_start/window_end needed).
--
-- DELIBERATE SIMPLIFICATION (documented, not silent): the reference
-- implementation resolves real geography via a MaxMind GeoLite2 database
-- download (city + country lookup by real IP address, see
-- GeographyOperator.java's DatabaseReader). That database isn't available
-- in this translation pass, and there's no SQL equivalent short of a
-- custom UDF embedding a real GeoIP database (a multi-MB binary MMDB
-- file), which is well beyond a query translation's scope. Substituted
-- here with a SYNTHETIC, deterministic lookup table (geo_ip_lookup) that
-- maps every possible IP first-octet (0-255) to one of 10 representative
-- country/city pairs (round-robin assignment) -- this exercises the same
-- QUERY SHAPE (per-event join against a static geo reference table,
-- same pattern as Sentiment Analysis's AFINN lexicon join) but does not
-- produce geographically meaningful output, since the underlying mapping
-- is fabricated, not real geographic data.
--
-- NOT YET VALIDATED against a live RisingWave instance -- deferred to a
-- later end-to-end pass, same as every other workload here.

